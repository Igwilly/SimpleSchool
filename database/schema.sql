CREATE TABLE Senha(
	email VARCHAR(50) PRIMARY KEY CHECK(email LIKE '%@%'),
	senha VARCHAR NOT NULL
);

CREATE TABLE Avaliacao(
	codigo INT PRIMARY KEY,
	titulo VARCHAR(50),
	descricao TEXT,
	materia VARCHAR(50),
	data DATE NOT NULL,
	hora_inicio TIME NOT NULL,
	hora_fim TIME NOT NULL,
	CHECK(hora_fim>hora_inicio)
);

CREATE TABLE Turma(
	codigo INT PRIMARY KEY,
	nome VARCHAR(50) NOT NULL,
	ano_letivo INT NOT NULL
);

CREATE TABLE Questao(
	codigo INT PRIMARY KEY,
	enunciado TEXT
);

CREATE TABLE Matricula_turma(
	matricula VARCHAR(50) PRIMARY KEY,
	codigo_turma INT NOT NULL REFERENCES Turma(codigo)
);

CREATE TABLE Aluno(
	ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	matricula VARCHAR(50) NOT NULL REFERENCES Matricula_turma(matricula),
	email VARCHAR(50) NOT NULL REFERENCES Senha(email),
	nome VARCHAR(100) NOT NULL,
	data_nasc DATE NOT NULL	
);

CREATE TABLE Professor(
	ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	CAD INT NOT NULL UNIQUE CHECK(CAD>0),
	disciplina VARCHAR(50) NOT NULL,
	email VARCHAR (50) NOT NULL REFERENCES Senha(email),
	nome VARCHAR(100) NOT NULL,
	data_nasc DATE NOT NULL
);

CREATE TABLE Questao_objetiva(
	codigo INT PRIMARY KEY REFERENCES Questao(codigo),
	imagem TEXT
);

CREATE TABLE Questao_dissertativa(
	codigo INT PRIMARY KEY REFERENCES Questao(codigo),
	resposta_esperada TEXT
);

CREATE TABLE Soluciona_avaliacao(
	ID_aluno INT NOT NULL REFERENCES Aluno(ID),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	data DATE NOT NULL,
	hora_inicio TIME NOT NULL,
	hora_fim TIME NOT NULL,
	PRIMARY KEY(ID_aluno, codigo_avaliacao, data), CHECK(hora_fim>hora_inicio)
);

CREATE TABLE Item_avaliacao(
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	codigo_questao INT NOT NULL REFERENCES Questao(codigo),
	valor NUMERIC(5, 2) NOT NULL CHECK(valor>=0 AND valor<=100),
	PRIMARY KEY(codigo_avaliacao, codigo_questao)
);

CREATE TABLE Resposta(
	ID_aluno INT NOT NULL REFERENCES Aluno(ID),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	codigo_questao INT NOT NULL REFERENCES Questao(codigo),
	nota NUMERIC(5, 2) NOT NULL CHECK(nota>=0 AND nota<=100),
	PRIMARY KEY(ID_aluno,codigo_avaliacao, codigo_questao),
	FOREIGN KEY(codigo_avaliacao, codigo_questao) REFERENCES Item_avaliacao(codigo_avaliacao, codigo_questao)
);

CREATE TABLE Resposta_dissertativa(
	ID_aluno INT NOT NULL REFERENCES Aluno(ID),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	codigo_questao INT NOT NULL REFERENCES Questao(codigo),
	data DATE NOT NULL,
	dissertacao TEXT,
	ID_professor INT NOT NULL REFERENCES Professor(ID),
	data_correcao DATE,
	PRIMARY KEY(ID_aluno,codigo_avaliacao, codigo_questao, data),
	FOREIGN KEY(ID_aluno, codigo_avaliacao, data) REFERENCES Soluciona_avaliacao(ID_aluno, codigo_avaliacao, data), CHECK(data_correcao IS NULL OR data_correcao>=data)
);

CREATE TABLE Alternativa(
	codigo_questao INT NOT NULL REFERENCES Questao(codigo),
	letra CHAR(1) NOT NULL CHECK(letra IN ('A', 'B', 'C', 'D', 'E')),
	texto TEXT,
	correta BOOLEAN NOT NULL,
	PRIMARY KEY(codigo_questao, letra)
);

CREATE TABLE Resposta_objetiva(
	ID_aluno INT NOT NULL REFERENCES Aluno(ID),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	codigo_questao INT NOT NULL REFERENCES Questao(codigo),
	data DATE NOT NULL,
	letra_alternativa CHAR(1) NOT NULL,
	PRIMARY KEY(ID_aluno, codigo_avaliacao, codigo_questao),
	FOREIGN KEY(ID_aluno, codigo_avaliacao, data) REFERENCES Soluciona_avaliacao(ID_aluno, codigo_avaliacao, data),
	FOREIGN KEY(codigo_questao, letra_alternativa) REFERENCES Alternativa(codigo_questao, letra)
);

CREATE TABLE Elabora(
	ID INT NOT NULL REFERENCES Professor(ID),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	PRIMARY KEY(ID, codigo_avaliacao)
);

CREATE TABLE Destinada(
	codigo_turma INT NOT NULL REFERENCES Turma(codigo),
	codigo_avaliacao INT NOT NULL REFERENCES Avaliacao(codigo),
	PRIMARY KEY(codigo_turma, codigo_avaliacao)
);